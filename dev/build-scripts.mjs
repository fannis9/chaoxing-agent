import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {root} from '../lib/config.mjs';
const source=readFileSync(join(root,'chaoxing-autoplay-v3.js'),'utf8');
const output='// Generated by npm run build:scripts. Edit chaoxing-autoplay-v3.js only.\n'
  +'window.__cxV3Options = {maxChapters:1};\ntry {\n'+source
  +'\n} finally { delete window.__cxV3Options; }\n';
const target=join(root,'chaoxing-autoplay-v3-one-chapter.js');
if(process.argv.includes('--check')) {
  if(readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output.replace(/\r\n/g,'\n'))
    throw new Error('单章脚本已过期，请运行 npm run build:scripts');
} else writeFileSync(target,output);
