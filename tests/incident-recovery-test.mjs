import assert from 'node:assert/strict';
import {decideRecovery,recoveryActions} from '../lib/incident-recovery.mjs';
const evidence={courseId:'1',chapterId:'2',nextAvailable:true,text:'任务数据不完整'};
const event={reason:'当前章节没有可识别的任务标签，且任务数据不完整'};
let calls=0;
const model=async()=>{calls++;return {text:JSON.stringify({action:'skip',reason:'任务数据缺失，保留待补做并继续'})}};
assert.equal((await decideRecovery({},event,evidence,0,model)).action,'skip');
assert.equal((await decideRecovery({},event,{...evidence,requiresUser:true},0,model)).action,'wait-user');
assert.equal(calls,1);
assert.deepEqual(recoveryActions(evidence,2),['skip']);
assert.deepEqual(recoveryActions({...evidence,videoFailure:true,allowVideoSkip:true},0),['reload','retry']);
assert.deepEqual(recoveryActions({...evidence,videoFailure:true,allowVideoSkip:false},2),[]);
assert.deepEqual(recoveryActions({...evidence,videoFailure:true,allowVideoSkip:true},2),['skip']);
assert.deepEqual(recoveryActions({...evidence,nextAvailable:false},2),[]);
assert.deepEqual(recoveryActions({...evidence,nextAvailable:false,finalChapter:true},2),['skip']);
const unavailable=async()=>{throw new Error('network')};
assert.equal((await decideRecovery({},event,evidence,0,unavailable)).action,'reload');
assert.equal((await decideRecovery({},event,evidence,2,unavailable)).action,'skip');
assert.equal((await decideRecovery({},event,evidence,2,async()=>({text:'{"action":"reload","reason":"repeat"}'}))).action,'skip');
assert.equal((await decideRecovery({},event,evidence,0,async()=>({text:'{"action":"eval","reason":"execute arbitrary code"}'}))).action,'reload');
console.log('PASS: AI action validation, identity gate, bounded retries, final chapter and model outage fallback');
